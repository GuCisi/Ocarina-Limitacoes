import json
w = json.load(open("shorts/ocarina/voice/words.json", encoding="utf-8"))
rows = ["  [%s, %d, %d, %d]," % (json.dumps(x["w"].strip(".,"), ensure_ascii=False), round(x["t0"] * 30), round(x["t1"] * 30), x["line"]) for x in w]
head = "// GENERATED by scripts/gen_words.py from shorts/ocarina/voice/words.json (30 fps): [word, first frame, last frame, script line]\n"
open("src/videos/ocarina/words.gen.ts", "w", encoding="utf-8").write(head + "export const WORDS: [string, number, number, number][] = [\n" + "\n".join(rows) + "\n];\n")
print(len(rows), "words")
